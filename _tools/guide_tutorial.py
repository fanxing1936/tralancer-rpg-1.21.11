def _see(*refs):
    """refs: (anchor, label) → 「详见 …」小字。"""
    return '<p class="tut-see">详见 ' + "、".join('<a href="#%s">%s</a>' % r for r in refs) + "</p>"


def _steps(items):
    """items: (title, body_html, tag)；tag 为 '' / '管理员' / '测试入口' / '可选'。"""
    out = []
    for title, body, tag in items:
        t = ('<span class="tut-who">%s</span>' % tag) if tag in ("管理员", "测试入口") else (
            ('<span class="opt">%s</span>' % tag) if tag else "")
        out.append("<li><div><h3>%s%s</h3>%s</div></li>" % (title, t, body))
    return '<ol class="steps">%s</ol>' % "".join(out)


def _table(head, rows):
    h = "".join("<th>%s</th>" % c for c in head)
    body = "".join("<tr>%s</tr>" % "".join("<td>%s</td>" % c for c in r) for r in rows)
    return '<div class="tw"><table><thead><tr>%s</tr></thead><tbody>%s</tbody></table></div>' % (h, body)


def _part(pid, title, right, inner):
    r = '<span class="rolls">%s</span>' % right if right else ""
    return '<div class="tut-part" id="%s"><h3 class="sub-h">%s%s</h3>%s</div>' % (pid, title, r, inner)


